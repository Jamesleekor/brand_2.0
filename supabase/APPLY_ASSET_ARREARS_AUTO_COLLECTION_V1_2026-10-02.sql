create or replace function public.teacher_collect_student_asset_arrears(
  p_classroom_id integer,
  p_student_id integer
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v_current_gold bigint:=0;
  v_reserved_auction bigint:=0;
  v_equalization_debt bigint:=0;
  v_equalization_reserve bigint:=0;
  v_min_balance bigint:=0;
  v_available_gold bigint:=0;
  v_result jsonb;
begin
  perform public.ensure_teacher_role();

  if p_classroom_id is null
     or p_classroom_id is distinct from public.current_classroom_id() then
    raise exception '담당 학급의 미납금만 징수할 수 있습니다.' using errcode='P0649';
  end if;

  if not exists(
    select 1
    from public.students s
    where s.id=p_student_id
      and s.classroom_id=p_classroom_id
      and s.transferred_at is null
  ) then
    raise exception '현재 학급의 활성 학생을 찾을 수 없습니다.' using errcode='P0650';
  end if;

  select coalesce(w.gold,0)::bigint
    into v_current_gold
  from public.wallets w
  where w.student_id=p_student_id
  for update;

  select coalesce(max(b.bid_amount),0)::bigint
    into v_reserved_auction
  from public.auction_bids b
  join public.auction_items i on i.id=b.auction_item_id
  join public.auctions a on a.id=i.auction_id
  where b.student_id=p_student_id
    and b.is_winning=true
    and b.invalidated_at is null
    and i.final_status is null
    and a.status='IN_PROGRESS'
    and a.current_item_id=i.id;

  select coalesce(sum(ep.amount-ep.paid_amount),0)::bigint
    into v_equalization_debt
  from public.equalization_contribution_payments ep
  where ep.student_id=p_student_id
    and ep.paid_amount<ep.amount;

  v_equalization_reserve:=least(v_equalization_debt,v_current_gold);
  v_min_balance:=greatest(v_reserved_auction,v_equalization_reserve);
  v_available_gold:=greatest(v_current_gold-v_min_balance,0);

  v_result:=public._collect_student_gold_asset_arrears(
    p_student_id,v_available_gold,'MANUAL',null,auth.uid()
  );

  return v_result || jsonb_build_object(
    'current_gold_before',v_current_gold,
    'auction_reserved_gold',v_reserved_auction,
    'equalization_reserved_gold',v_equalization_reserve,
    'available_gold_before',v_available_gold
  );
end;
$function$;

revoke all on function public.teacher_collect_student_asset_arrears(integer,integer)
from public,anon;
grant execute on function public.teacher_collect_student_asset_arrears(integer,integer)
to authenticated,service_role;


COMMIT;
