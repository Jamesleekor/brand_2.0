    SELECT count(*)
    FROM public.daily_quest_checks c
    JOIN public.daily_quest_reports r ON r.id=c.report_id
    WHERE r.status IN ('DRAFT','RETURNED','SUBMITTED')
      AND c.result='UNCHECKED'
      AND NOT public.is_official_participant(c.student_id)
  )
) AS daily_quest_welfare_postcheck;
