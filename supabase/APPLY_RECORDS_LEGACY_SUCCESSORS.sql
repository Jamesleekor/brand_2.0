  returning s.id into v_updated;

  if v_updated is null then
    raise exception '[RECORDS_LEGACY] registered successor not found.'
      using errcode = 'P0969';
  end if;

  return public.teacher_get_records_legacy_successors();
end;
$function$;

-- ----------------------------------------------------------------------------
-- Teacher: lock the final successor roster for the inheritance ceremony.
-- ----------------------------------------------------------------------------
create or replace function public.teacher_lock_records_legacy_successors()
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_classroom_id integer := public.current_classroom_id();
  v_owner_teacher_user_id uuid;
  v_school_year integer;
  v_event public.records_legacy_events%rowtype;
  v_count integer := 0;
begin
  perform public.ensure_teacher_role();

  if auth.uid() is null or v_classroom_id is null then
    raise exception '[RECORDS_LEGACY] authenticated teacher context is required.'
      using errcode = 'P0975';
  end if;

  select c.teacher_user_id, c.school_year
    into v_owner_teacher_user_id, v_school_year
  from public.classrooms c
  where c.id = v_classroom_id;

  select e.* into v_event
  from public.records_legacy_events e
  where e.owner_teacher_user_id = v_owner_teacher_user_id
    and e.school_year = v_school_year
  for update;

  if v_event.id is null then
    raise exception '[RECORDS_LEGACY] event has not started.' using errcode = 'P0970';
  end if;

  if v_event.status not in ('OPEN', 'UNSEALED') then
    raise exception '[RECORDS_LEGACY] only an open successor roster can be locked.' using errcode = 'P0971';
  end if;

  select count(*)::integer into v_count
  from public.records_legacy_successors s
  where s.event_id = v_event.id and s.registered_at is not null;

  if v_count < v_event.minimum_successors then
    raise exception '[RECORDS_LEGACY] minimum successor count has not been reached.' using errcode = 'P0972';
  end if;

  update public.records_legacy_events e
  set status = 'LOCKED',
      locked_at = now(),
      locked_successor_count = v_count,
      updated_at = now()
  where e.id = v_event.id;

  return public.teacher_get_records_legacy_successors();
end;
$function$;

-- ----------------------------------------------------------------------------
-- Teacher: unlock a roster that was locked by mistake. The event stays
-- UNSEALED once it has ever reached 12.
-- ----------------------------------------------------------------------------
create or replace function public.teacher_unlock_records_legacy_successors()
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_classroom_id integer := public.current_classroom_id();
  v_owner_teacher_user_id uuid;
  v_school_year integer;
  v_event public.records_legacy_events%rowtype;
begin
  perform public.ensure_teacher_role();

  if auth.uid() is null or v_classroom_id is null then
    raise exception '[RECORDS_LEGACY] authenticated teacher context is required.'
      using errcode = 'P0976';
  end if;

  select c.teacher_user_id, c.school_year
    into v_owner_teacher_user_id, v_school_year
  from public.classrooms c
  where c.id = v_classroom_id;

  select e.* into v_event
  from public.records_legacy_events e
  where e.owner_teacher_user_id = v_owner_teacher_user_id
    and e.school_year = v_school_year
  for update;

  if v_event.id is null or v_event.status <> 'LOCKED' then
    raise exception '[RECORDS_LEGACY] only a locked event can be unlocked.' using errcode = 'P0973';
  end if;

  update public.records_legacy_events e
  set status = case when e.unsealed_at is not null then 'UNSEALED' else 'OPEN' end,
      locked_at = null,
      locked_successor_count = null,
      updated_at = now()
  where e.id = v_event.id;

  return public.teacher_get_records_legacy_successors();
end;
$function$;

revoke all on function public.student_get_records_legacy_successor_state() from public, anon;
revoke all on function public.student_discover_records_legacy_seal() from public, anon;
revoke all on function public.student_confirm_records_legacy_seal() from public, anon;
revoke all on function public.student_register_records_legacy_successor(text, text) from public, anon;
revoke all on function public.teacher_get_records_legacy_successors() from public, anon;
revoke all on function public.teacher_reset_records_legacy_successor(integer) from public, anon;
revoke all on function public.teacher_lock_records_legacy_successors() from public, anon;
revoke all on function public.teacher_unlock_records_legacy_successors() from public, anon;

grant execute on function public.student_get_records_legacy_successor_state() to authenticated;
grant execute on function public.student_discover_records_legacy_seal() to authenticated;
grant execute on function public.student_confirm_records_legacy_seal() to authenticated;
grant execute on function public.student_register_records_legacy_successor(text, text) to authenticated;
grant execute on function public.teacher_get_records_legacy_successors() to authenticated;
grant execute on function public.teacher_reset_records_legacy_successor(integer) to authenticated;
grant execute on function public.teacher_lock_records_legacy_successors() to authenticated;
grant execute on function public.teacher_unlock_records_legacy_successors() to authenticated;

