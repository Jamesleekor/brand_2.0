  constraint expedition_settings_publish_weekday_chk check (publish_weekday between 1 and 7),
  constraint expedition_settings_world_duration_chk check (world_effect_duration_hours = 168),
  constraint expedition_settings_world_threshold_chk check (world_trace_lv1>0 and world_trace_lv1<world_trace_lv2 and world_trace_lv2<world_trace_lv3),
  constraint expedition_settings_story_threshold_chk check (story_trace_faint>0 and story_trace_faint<story_trace_discovery and story_trace_discovery<story_trace_active and story_trace_active<story_trace_breakthrough)
