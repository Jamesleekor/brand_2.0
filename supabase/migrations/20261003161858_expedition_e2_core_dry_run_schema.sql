create table public.expedition_settings (
  classroom_id integer primary key references public.classrooms(id) on delete cascade,
  schema_version text not null default 'EXPEDITION_V1_4',
  is_core_enabled boolean not null default false,
  is_student_ui_enabled boolean not null default false,
  is_scheduler_enabled boolean not null default false,
  is_reward_grant_enabled boolean not null default false,
  publish_weekday smallint not null default 5,
  publish_time_kst time not null default time '17:00',
  sat_open_time_kst time not null default time '00:00',
  sun_open_time_kst time not null default time '00:00',
  settle_time_kst time not null default time '00:05',
  world_effect_start_time_kst time not null default time '06:00',
  world_effect_duration_hours smallint not null default 168,
  world_trace_lv1 smallint not null default 12,
  world_trace_lv2 smallint not null default 24,
  world_trace_lv3 smallint not null default 40,
  map_mastery_threshold smallint not null default 24,
  story_trace_faint smallint not null default 1,
  story_trace_discovery smallint not null default 5,
  story_trace_active smallint not null default 10,
  story_trace_breakthrough smallint not null default 18,
  reward_config jsonb not null default '{}'::jsonb,
  world_effect_config jsonb not null default '{}'::jsonb,
