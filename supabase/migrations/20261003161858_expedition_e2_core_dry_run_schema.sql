create table public.expedition_weeks (
  id bigint generated by default as identity primary key,
  season_id bigint not null references public.expedition_seasons(id) on delete restrict,
  classroom_id integer not null references public.classrooms(id) on delete restrict,
  week_index integer not null, week_start_date date not null, generation_no integer not null default 1,
  week_seed text not null, status text not null default 'DRAFT', reward_mode text not null default 'DRY_RUN',
  publish_at timestamptz not null, sat_open_at timestamptz not null, sun_open_at timestamptz not null,
  sun_close_at timestamptz not null, settle_at timestamptz not null,
  fit_formula_version text not null default 'ELEM_70_30_V1',
  config_snapshot jsonb not null default '{}'::jsonb, reward_pool_snapshot jsonb not null default '{}'::jsonb,
  dominant_week_site_id bigint null, world_effect_level smallint null,
  published_at timestamptz null, resolved_at timestamptz null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint expedition_weeks_index_chk check (week_index>=1),
  constraint expedition_weeks_generation_chk check (generation_no>=1),
  constraint expedition_weeks_seed_chk check (btrim(week_seed)<>''),
  constraint expedition_weeks_status_chk check (status in ('DRAFT','PUBLISHED','SETTLED','CANCELLED')),
  constraint expedition_weeks_reward_mode_chk check (reward_mode in ('DRY_RUN','LIVE')),
  constraint expedition_weeks_formula_chk check (fit_formula_version='ELEM_70_30_V1'),
  constraint expedition_weeks_window_order_chk check (publish_at<sat_open_at and sat_open_at<sun_open_at and sun_open_at<sun_close_at and sun_close_at<=settle_at),
  constraint expedition_weeks_effect_level_chk check (world_effect_level is null or world_effect_level between 0 and 3),
  unique(classroom_id,week_start_date)
);
create index expedition_weeks_classroom_status_idx on public.expedition_weeks(classroom_id,status,week_start_date desc);
create trigger expedition_weeks_set_updated_at before update on public.expedition_weeks for each row execute function public.expedition_set_updated_at();

