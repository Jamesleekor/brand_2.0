do $preflight$
begin
  if to_regclass('public.character_element_profiles') is null
     or to_regclass('public.character_expedition_profiles') is null
     or to_regclass('public.expedition_specialties') is null then
    raise exception 'EXPEDITION_E2_REQUIRES_E1_BASELINE' using errcode='P0E20';
  end if;
  if (select count(*) from public.character_element_profiles) <> 79
     or (select count(*) from public.character_expedition_profiles where profile_status='ACTIVE') <> 79 then
    raise exception 'EXPEDITION_E2_E1_COVERAGE_INVALID' using errcode='P0E21';
  end if;
end
$preflight$;

