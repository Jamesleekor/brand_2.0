create or replace function public.student_get_my_asset_arrears()
returns jsonb
language plpgsql
stable security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v_student_id integer:=public.current_student_id();
  v_classroom_id integer:=public.current_classroom_id();
  v_result jsonb;
begin
  if v_student_id is null or v_classroom_id is null then
    raise exception '학생 정보를 확인할 수 없습니다.' using errcode='P0636';
  end if;

  select jsonb_build_object(
    'student_id',v_student_id,
    'classroom_id',v_classroom_id,
    'total_items',count(*) filter(where a.status in ('UNPAID','PARTIAL')),
    'totals',jsonb_build_object(
      'BV',coalesce(sum(a.assessed_amount-a.paid_amount)
        filter(where a.status in ('UNPAID','PARTIAL') and a.value_token='BV'),0),
      'GOLD',coalesce(sum(a.assessed_amount-a.paid_amount)
        filter(where a.status in ('UNPAID','PARTIAL') and a.value_token='GOLD'),0),
      'CRYSTAL',coalesce(sum(a.assessed_amount-a.paid_amount)
        filter(where a.status in ('UNPAID','PARTIAL') and a.value_token='CRYSTAL'),0)
    ),
    'entries',coalesce(jsonb_agg(
      jsonb_build_object(
        'id',a.id,
        'value_token',a.value_token::text,
        'assessed_amount',a.assessed_amount,
        'paid_amount',a.paid_amount,
        'outstanding_amount',a.assessed_amount-a.paid_amount,
        'reason',a.reason,
        'status',a.status,
        'created_at',a.created_at
      ) order by a.created_at desc,a.id desc
    ) filter(where a.status in ('UNPAID','PARTIAL')),'[]'::jsonb)
  )
  into v_result
  from public.student_asset_arrears a
  where a.student_id=v_student_id
    and a.classroom_id=v_classroom_id;

  return coalesce(v_result,jsonb_build_object(
    'student_id',v_student_id,
    'classroom_id',v_classroom_id,
    'total_items',0,
    'totals',jsonb_build_object('BV',0,'GOLD',0,'CRYSTAL',0),
    'entries','[]'::jsonb
  ));
end;
$function$;

