create or replace function public._teacher_apply_asset_deduction(
  p_student_id integer,
  p_value_token public.value_token_type,
  p_requested_amount bigint,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v_classroom_id integer;
  v_current bigint:=0;
  v_reserved_auction bigint:=0;
  v_equalization_debt bigint:=0;
  v_equalization_reserve bigint:=0;
  v_min_balance bigint:=0;
  v_available bigint:=0;
  v_collected bigint:=0;
  v_outstanding bigint:=0;
  v_tx_id bigint:=null;
  v_arrear_id bigint:=null;
  v_source public.transaction_source_type;
  v_new_balance bigint:=0;
begin
  if p_requested_amount is null or p_requested_amount<=0 then
    raise exception '차감 금액은 1 이상이어야 합니다.' using errcode='P0634';
  end if;

  select s.classroom_id into v_classroom_id
  from public.students s
  where s.id=p_student_id and s.transferred_at is null;

  if v_classroom_id is null then
    raise exception '활성 학생을 찾을 수 없습니다.' using errcode='P0632';
  end if;

  perform 1 from public.wallets w where w.student_id=p_student_id for update;

  select case p_value_token
    when 'BV'::public.value_token_type then w.bv
    when 'GOLD'::public.value_token_type then w.gold
    when 'CRYSTAL'::public.value_token_type then w.crystal
  end
  into v_current
  from public.wallets w
  where w.student_id=p_student_id;

  v_current:=coalesce(v_current,0);

  if p_value_token='GOLD'::public.value_token_type then
    select coalesce(max(b.bid_amount),0)::bigint
    into v_reserved_auction
    from public.auction_bids b
    join public.auction_items i on i.id=b.auction_item_id
    join public.auctions a on a.id=i.auction_id
    where b.student_id=p_student_id
      and b.is_winning=true
      and b.invalidated_at is null
      and i.final_status is null
      and a.status='IN_PROGRESS'
      and a.current_item_id=i.id;

    select coalesce(sum(ep.amount-ep.paid_amount),0)::bigint
    into v_equalization_debt
    from public.equalization_contribution_payments ep
    where ep.student_id=p_student_id
      and ep.paid_amount<ep.amount;

    v_equalization_reserve:=least(v_equalization_debt,v_current);
    v_min_balance:=greatest(v_reserved_auction,v_equalization_reserve);
  else
    v_min_balance:=0;
  end if;

  v_available:=greatest(v_current-v_min_balance,0);
  v_collected:=least(p_requested_amount,v_available);
  v_outstanding:=p_requested_amount-v_collected;

  if p_value_token='BV'::public.value_token_type then
    v_source:='BV_REVOKE'::public.transaction_source_type;
  else
    v_source:='TEACHER_DEDUCT'::public.transaction_source_type;
  end if;

  if v_collected>0 then
    v_tx_id:=public.create_transaction(
      p_student_id,
      p_value_token,
      -v_collected,
      v_source,
      null,
      0,
      case p_value_token
        when 'BV'::public.value_token_type then '[교사 BV 차감] '||p_reason
        when 'GOLD'::public.value_token_type then '[교사 골드 차감] '||p_reason
        else '[교사 크리스탈 차감] '||p_reason
      end
    );
  end if;

  if v_outstanding>0 then
    insert into public.student_asset_arrears(
      classroom_id,student_id,value_token,assessed_amount,paid_amount,
      reason,status,initial_transaction_id,created_by
    ) values (
      v_classroom_id,p_student_id,p_value_token,p_requested_amount,v_collected,
      p_reason,
      case when v_collected>0 then 'PARTIAL' else 'UNPAID' end,
      v_tx_id,auth.uid()
    )
    returning id into v_arrear_id;
  end if;

  select case p_value_token
    when 'BV'::public.value_token_type then w.bv
    when 'GOLD'::public.value_token_type then w.gold
    when 'CRYSTAL'::public.value_token_type then w.crystal
  end
  into v_new_balance
  from public.wallets w
  where w.student_id=p_student_id;

  return jsonb_build_object(
    'transaction_id',v_tx_id,
    'arrear_id',v_arrear_id,
    'requested_amount',p_requested_amount,
    'collected_amount',v_collected,
    'outstanding_amount',v_outstanding,
    'new_balance',coalesce(v_new_balance,0),
    'reserved_auction',v_reserved_auction,
    'equalization_reserve',v_equalization_reserve
  );
end;
$function$;

revoke all on function public._teacher_apply_asset_deduction(integer,public.value_token_type,bigint,text)
from public,anon,authenticated;
grant execute on function public._teacher_apply_asset_deduction(integer,public.value_token_type,bigint,text)
to service_role;

create or replace function public.teacher_adjust_student_assets_v2(
  p_student_ids integer[],
  p_value_token public.value_token_type,
  p_amount bigint,
  p_reason text,
  p_tax_rate_percent numeric default null
)
returns table(
  student_id integer,
  transaction_id bigint,
  new_balance bigint,
  tax_amount bigint,
  arrear_amount bigint
)
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v_classroom_id integer;
  v_requested_count integer;
  v_valid_count integer;
  v_student_id integer;
  v_reason text;
  v_result jsonb;
  v_tx_id bigint;
  v_new_balance bigint;
  v_tax bigint;
  v_arrear bigint;
begin
  if auth.uid() is null then
    raise exception '로그인이 필요합니다.' using errcode='P0600';
  end if;
  perform public.ensure_teacher_role();

  v_requested_count:=cardinality(p_student_ids);
  if p_student_ids is null or coalesce(v_requested_count,0)<1 then
    raise exception '대상 학생을 한 명 이상 선택해주세요.' using errcode='P0601';
  end if;
  if v_requested_count>100 then
    raise exception '한 번에 처리할 수 있는 학생은 최대 100명입니다.' using errcode='P0602';
  end if;
  if (select count(distinct x.id) from unnest(p_student_ids) x(id))<>v_requested_count
     or exists(select 1 from unnest(p_student_ids) x(id) where x.id is null) then
    raise exception '학생 목록에 중복 또는 잘못된 값이 있습니다.' using errcode='P0603';
  end if;

  if p_value_token is null or p_value_token not in (
    'BV'::public.value_token_type,
    'GOLD'::public.value_token_type,
    'CRYSTAL'::public.value_token_type
  ) then
    raise exception '교사 조정은 BV, GOLD 또는 CRYSTAL만 가능합니다.' using errcode='P0604';
  end if;

  if p_amount is null or p_amount=0 or abs(p_amount)>10000000 then
    raise exception '금액은 1 이상 10,000,000 이하이어야 합니다.' using errcode='P0605';
  end if;

  v_reason:=btrim(coalesce(p_reason,''));
  if char_length(v_reason)<2 or char_length(v_reason)>200 then
    raise exception '사유는 2자 이상 200자 이하로 입력해주세요.' using errcode='P0606';
  end if;

  v_classroom_id:=public.current_classroom_id();
  if v_classroom_id is null then
    raise exception '담당 학급을 확인할 수 없습니다.' using errcode='P0607';
  end if;

  select count(*) into v_valid_count
  from public.students s
  where s.id=any(p_student_ids)
    and s.classroom_id=v_classroom_id
    and s.transferred_at is null
    and s.role in ('STUDENT','STUDENT_LEADER','GUARD');

  if v_valid_count<>v_requested_count then
    raise exception '선택한 학생 중 담당 학급의 활성 학생이 아닌 대상이 있습니다.' using errcode='P0608';
  end if;

  if p_amount>0
     and p_value_token='GOLD'::public.value_token_type
     and p_tax_rate_percent is not null then
    perform public._teacher_set_income_tax_rate_percent(v_classroom_id,p_tax_rate_percent);
  end if;

  for v_student_id in
    select x.id from unnest(p_student_ids) x(id) order by x.id
  loop
    v_tx_id:=null;
    v_tax:=0;
    v_arrear:=0;

    if p_amount>0 then
      if p_value_token='GOLD'::public.value_token_type then
        v_result:=public._teacher_grant_gold_with_tax(v_student_id,p_amount,v_reason);
        v_tx_id:=nullif(v_result->>'transaction_id','')::bigint;
        v_new_balance:=coalesce((v_result->>'new_balance')::bigint,0);
        v_tax:=coalesce((v_result->>'tax_amount')::bigint,0);
      else
        v_tx_id:=public.create_transaction(
          v_student_id,
          p_value_token,
          p_amount,
          'TEACHER_GRANT'::public.transaction_source_type,
          null,
          0,
          case p_value_token
            when 'BV'::public.value_token_type then '[교사 BV 지급] '||v_reason
            else '[교사 크리스탈 지급] '||v_reason
          end
        );

        select case p_value_token
          when 'BV'::public.value_token_type then w.bv
          else w.crystal
        end
        into v_new_balance
        from public.wallets w
        where w.student_id=v_student_id;
      end if;
    else
      v_result:=public._teacher_apply_asset_deduction(
        v_student_id,p_value_token,abs(p_amount),v_reason
      );
      v_tx_id:=nullif(v_result->>'transaction_id','')::bigint;
      v_new_balance:=coalesce((v_result->>'new_balance')::bigint,0);
      v_arrear:=coalesce((v_result->>'outstanding_amount')::bigint,0);
    end if;

    student_id:=v_student_id;
    transaction_id:=v_tx_id;
    new_balance:=v_new_balance;
    tax_amount:=v_tax;
    arrear_amount:=v_arrear;
    return next;
  end loop;
end;
$function$;

