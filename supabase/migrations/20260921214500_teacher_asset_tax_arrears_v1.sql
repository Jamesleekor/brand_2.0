security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v_rate numeric;
begin
  if p_rate_percent is null or p_rate_percent<0 or p_rate_percent>=100 then
    raise exception '소득세율은 0 이상 100 미만으로 입력해주세요.' using errcode='P0631';
  end if;

  v_rate:=round(p_rate_percent,2)/100;

  insert into public.classroom_settings(classroom_id,setting_key,setting_value)
  values (p_classroom_id,'income_tax_rate',to_jsonb(v_rate))
  on conflict (classroom_id,setting_key) do update
  set setting_value=excluded.setting_value,
      updated_at=now();

  return v_rate;
end;
