create or replace function public._teacher_grant_gold_with_tax(
  p_student_id integer,
  p_gross_amount bigint,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v_classroom_id integer;
  v_tax bigint;
  v_net bigint;
  v_tx_id bigint;
  v_new_gold bigint;
begin
  if p_gross_amount is null or p_gross_amount<=0 then
    return jsonb_build_object(
      'transaction_id',null,
      'gross_amount',0,
      'tax_amount',0,
      'net_amount',0,
      'new_balance',(select coalesce(w.gold,0) from public.wallets w where w.student_id=p_student_id)
    );
  end if;

  select s.classroom_id into v_classroom_id
  from public.students s
  where s.id=p_student_id and s.transferred_at is null;

  if v_classroom_id is null then
    raise exception '활성 학생을 찾을 수 없습니다.' using errcode='P0632';
  end if;

  v_tax:=public.calculate_income_tax_for_student(p_gross_amount,p_student_id);
  v_net:=p_gross_amount-v_tax;

  if v_net<=0 then
    raise exception '적용 세율로 인해 실수령 골드가 0 이하가 됩니다.' using errcode='P0633';
  end if;

  v_tx_id:=public.create_transaction(
    p_student_id,
    'GOLD'::public.value_token_type,
    v_net,
    'TEACHER_GRANT'::public.transaction_source_type,
    null,
    v_tax,
    format('[교사 지급] %s · 총 %s GOLD / 세금 %s / 실수령 %s',
      p_reason,p_gross_amount,v_tax,v_net)
  );

  if v_tax>0 then
    insert into public.classroom_settings(classroom_id,setting_key,setting_value)
    values (v_classroom_id,'welfare_balance',to_jsonb(v_tax))
    on conflict (classroom_id,setting_key) do update
    set setting_value=to_jsonb(
      coalesce((public.classroom_settings.setting_value)::text::bigint,0)+v_tax
    ),
    updated_at=now();
  end if;

  select w.gold into v_new_gold
  from public.wallets w
  where w.student_id=p_student_id;

  return jsonb_build_object(
    'transaction_id',v_tx_id,
    'gross_amount',p_gross_amount,
    'tax_amount',v_tax,
    'net_amount',v_net,
    'new_balance',v_new_gold
  );
end;
$function$;

