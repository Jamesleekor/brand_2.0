create or replace function public.teacher_adjust_student_assets_combined(
  p_student_ids integer[],
  p_bv_amount bigint,
  p_gold_amount bigint,
  p_operation text,
  p_reason text,
  p_tax_rate_percent numeric default null
)
returns table(
  student_id integer,
  bv_transaction_id bigint,
  gold_transaction_id bigint,
  new_bv bigint,
  new_gold bigint,
  gold_tax_amount bigint,
  bv_arrear_amount bigint,
  gold_arrear_amount bigint
)
language plpgsql
security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v_classroom_id integer;
  v_requested_count integer;
  v_valid_count integer;
  v_student_id integer;
  v_reason text;
  v_operation text;
  v_bv_result jsonb;
  v_gold_result jsonb;
  v_bv_tx bigint;
  v_gold_tx bigint;
  v_new_bv bigint;
  v_new_gold bigint;
  v_gold_tax bigint;
  v_bv_arrear bigint;
  v_gold_arrear bigint;
begin
  if auth.uid() is null then
    raise exception '로그인이 필요합니다.' using errcode='P0600';
  end if;
  perform public.ensure_teacher_role();

  v_requested_count:=cardinality(p_student_ids);
  if p_student_ids is null or coalesce(v_requested_count,0)<1 then
    raise exception '대상 학생을 한 명 이상 선택해주세요.' using errcode='P0601';
  end if;
  if v_requested_count>100 then
    raise exception '한 번에 처리할 수 있는 학생은 최대 100명입니다.' using errcode='P0602';
  end if;
  if (select count(distinct x.id) from unnest(p_student_ids) x(id))<>v_requested_count
     or exists(select 1 from unnest(p_student_ids) x(id) where x.id is null) then
    raise exception '학생 목록에 중복 또는 잘못된 값이 있습니다.' using errcode='P0603';
  end if;

  p_bv_amount:=coalesce(p_bv_amount,0);
  p_gold_amount:=coalesce(p_gold_amount,0);
  if p_bv_amount<0 or p_gold_amount<0
     or p_bv_amount>10000000 or p_gold_amount>10000000
     or (p_bv_amount=0 and p_gold_amount=0) then
    raise exception 'BV와 GOLD는 0~10,000,000 정수이며 둘 중 하나 이상은 1 이상이어야 합니다.'
      using errcode='P0621';
  end if;

  v_operation:=upper(btrim(coalesce(p_operation,'')));
  if v_operation not in ('GRANT','DEDUCT') then
    raise exception '처리 방식은 GRANT 또는 DEDUCT여야 합니다.' using errcode='P0635';
  end if;

  v_reason:=btrim(coalesce(p_reason,''));
  if char_length(v_reason)<2 or char_length(v_reason)>200 then
    raise exception '사유는 2자 이상 200자 이하로 입력해주세요.' using errcode='P0606';
  end if;

  v_classroom_id:=public.current_classroom_id();
  if v_classroom_id is null then
    raise exception '담당 학급을 확인할 수 없습니다.' using errcode='P0607';
  end if;

  select count(*) into v_valid_count
  from public.students s
  where s.id=any(p_student_ids)
    and s.classroom_id=v_classroom_id
    and s.transferred_at is null
    and s.role in ('STUDENT','STUDENT_LEADER','GUARD');

  if v_valid_count<>v_requested_count then
    raise exception '선택한 학생 중 담당 학급의 활성 학생이 아닌 대상이 있습니다.' using errcode='P0608';
  end if;

  if v_operation='GRANT' and p_gold_amount>0 and p_tax_rate_percent is not null then
    perform public._teacher_set_income_tax_rate_percent(v_classroom_id,p_tax_rate_percent);
  end if;

  for v_student_id in
    select x.id from unnest(p_student_ids) x(id) order by x.id
  loop
    v_bv_tx:=null;
    v_gold_tx:=null;
    v_gold_tax:=0;
    v_bv_arrear:=0;
    v_gold_arrear:=0;

    if p_bv_amount>0 then
      if v_operation='GRANT' then
        v_bv_tx:=public.create_transaction(
          v_student_id,'BV'::public.value_token_type,p_bv_amount,
          'TEACHER_GRANT'::public.transaction_source_type,null,0,
          '[교사 BV+골드 동시 지급 / BV] '||v_reason
        );
      else
        v_bv_result:=public._teacher_apply_asset_deduction(
          v_student_id,'BV'::public.value_token_type,p_bv_amount,v_reason
        );
        v_bv_tx:=nullif(v_bv_result->>'transaction_id','')::bigint;
        v_bv_arrear:=coalesce((v_bv_result->>'outstanding_amount')::bigint,0);
      end if;
    end if;

    if p_gold_amount>0 then
      if v_operation='GRANT' then
        v_gold_result:=public._teacher_grant_gold_with_tax(
          v_student_id,p_gold_amount,v_reason
        );
        v_gold_tx:=nullif(v_gold_result->>'transaction_id','')::bigint;
        v_gold_tax:=coalesce((v_gold_result->>'tax_amount')::bigint,0);
      else
        v_gold_result:=public._teacher_apply_asset_deduction(
          v_student_id,'GOLD'::public.value_token_type,p_gold_amount,v_reason
        );
        v_gold_tx:=nullif(v_gold_result->>'transaction_id','')::bigint;
        v_gold_arrear:=coalesce((v_gold_result->>'outstanding_amount')::bigint,0);
      end if;
    end if;

    select w.bv,w.gold into v_new_bv,v_new_gold
    from public.wallets w where w.student_id=v_student_id;

    student_id:=v_student_id;
    bv_transaction_id:=v_bv_tx;
    gold_transaction_id:=v_gold_tx;
    new_bv:=coalesce(v_new_bv,0);
    new_gold:=coalesce(v_new_gold,0);
    gold_tax_amount:=v_gold_tax;
    bv_arrear_amount:=v_bv_arrear;
    gold_arrear_amount:=v_gold_arrear;
    return next;
  end loop;
end;
$function$;

