create table if not exists public.student_asset_arrears (
  id bigint generated by default as identity primary key,
  classroom_id integer not null references public.classrooms(id),
  student_id integer not null references public.students(id),
  value_token public.value_token_type not null,
  assessed_amount bigint not null check (assessed_amount > 0),
  paid_amount bigint not null default 0 check (paid_amount >= 0 and paid_amount <= assessed_amount),
  reason text not null check (char_length(btrim(reason)) between 2 and 200),
  status text not null default 'UNPAID'
    check (status in ('UNPAID','PARTIAL','PAID','WAIVED')),
  initial_transaction_id bigint references public.transactions(id),
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  settled_at timestamptz,
  waived_at timestamptz
);

create index if not exists idx_student_asset_arrears_student_open
  on public.student_asset_arrears(student_id, value_token, created_at, id)
  where status in ('UNPAID','PARTIAL');

create index if not exists idx_student_asset_arrears_classroom_open
  on public.student_asset_arrears(classroom_id, status, created_at, id);

alter table public.student_asset_arrears enable row level security;
revoke all on public.student_asset_arrears from public, anon, authenticated;

create or replace function public.teacher_get_asset_adjustment_config(p_classroom_id integer)
returns jsonb
language plpgsql
stable security definer
set search_path to 'public','pg_temp'
as $function$
declare
  v_setting jsonb;
  v_raw numeric;
  v_rate numeric;
begin
  perform public.ensure_teacher_role();

  if p_classroom_id is null
     or p_classroom_id is distinct from public.current_classroom_id() then
    raise exception '담당 학급의 자산 설정만 조회할 수 있습니다.' using errcode='P0630';
  end if;

  select cs.setting_value into v_setting
  from public.classroom_settings cs
  where cs.classroom_id=p_classroom_id
    and cs.setting_key='income_tax_rate';

  v_raw:=coalesce((v_setting)::text::numeric,0.10);
  if v_raw between 0 and 1 then
    v_rate:=v_raw*100;
  elsif v_raw>1 and v_raw<100 then
    v_rate:=v_raw;
  else
    v_rate:=10;
  end if;

  return jsonb_build_object(
    'classroom_id',p_classroom_id,
    'income_tax_rate_percent',round(v_rate,2)
  );
end;
$function$;

revoke all on function public.teacher_get_asset_adjustment_config(integer) from public,anon;
grant execute on function public.teacher_get_asset_adjustment_config(integer) to authenticated,service_role;

