-- ============================================================================
-- B.R.A.N.D 2.0 — 레이드 전리품 획득식 V1.2 · 1/3 (enum 선행 적용)
--
-- 왜 따로 실행하나요?
--   PostgreSQL은 enum 값을 새로 추가한 그 트랜잭션 안에서는 그 값을 쓸 수 없습니다.
--   그래서 이 파일을 "먼저, 단독으로" 실행하고 성공한 뒤에 02, 03 파일을 실행합니다.
--
-- 무엇을 하나요?
--   거래 출처 종류(transaction_source_type)에 'RAID_LOOT'(레이드 전리품)를 추가합니다.
--   기존 'RAID_REWARD'는 고유 인덱스 ux_transactions_raid_reward_once 때문에
--   학생·레이드·재화당 1건만 허용되고, 그 1건은 기본 레이드 보상이 이미 사용합니다.
--
-- 안전성
--   값 추가만 합니다. 기존 값·기존 거래·기존 함수는 바뀌지 않습니다.
--   이 값을 아무도 쓰지 않으면 기존 동작에 영향이 없습니다.
--   (enum 값은 한 번 추가하면 삭제할 수 없습니다.)
-- ============================================================================

ALTER TYPE public.transaction_source_type ADD VALUE IF NOT EXISTS 'RAID_LOOT';
