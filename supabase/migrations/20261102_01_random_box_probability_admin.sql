-- Random box probability administration (2026-11-02)
-- Teacher-editable weights, student disclosure toggle, presets, and change history.

create table if not exists public.random_box_settings (
  classroom_id integer not null references public.classrooms(id) on delete cascade,
  random_box_key text not null,
  reveal_probabilities boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid null,
  primary key (classroom_id, random_box_key)
);
alter table public.random_box_settings enable row level security;
revoke all on public.random_box_settings from public, anon, authenticated;

create table if not exists public.random_box_probability_history (
  id bigint generated by default as identity primary key,
  classroom_id integer not null references public.classrooms(id) on delete cascade,
  random_box_key text not null,
  previous_weights jsonb not null,
  new_weights jsonb not null,
  reveal_probabilities boolean not null,
  changed_by uuid null,
  change_note text null,
  created_at timestamptz not null default now()
);
alter table public.random_box_probability_history enable row level security;
revoke all on public.random_box_probability_history from public, anon, authenticated;

create index if not exists random_box_probability_history_lookup_idx
  on public.random_box_probability_history(classroom_id, random_box_key, created_at desc, id desc);

create table if not exists public.random_box_probability_presets (
  id bigint generated by default as identity primary key,
  classroom_id integer not null references public.classrooms(id) on delete cascade,
  random_box_key text not null,
  preset_name text not null,
  weights jsonb not null,
  created_by uuid null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (classroom_id, random_box_key, preset_name)
);
alter table public.random_box_probability_presets enable row level security;
revoke all on public.random_box_probability_presets from public, anon, authenticated;

insert into public.random_box_settings(classroom_id, random_box_key, reveal_probabilities)
select distinct classroom_id, random_box_key, true
from public.random_box_reward_catalog
where random_box_key='SUMMER_2026_RB1'
on conflict (classroom_id, random_box_key) do nothing;

insert into public.random_box_probability_presets(classroom_id, random_box_key, preset_name, weights)
select classroom_id, random_box_key, '기본 확률',
       jsonb_object_agg(reward_code, weight_bp order by display_order)
from public.random_box_reward_catalog
where random_box_key='SUMMER_2026_RB1' and is_active=true
group by classroom_id, random_box_key
on conflict (classroom_id, random_box_key, preset_name) do nothing;

create or replace function public.teacher_get_random_box_probability_admin(
  p_classroom_id integer,
  p_random_box_key text default 'SUMMER_2026_RB1'
) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_rewards jsonb; v_presets jsonb; v_history jsonb; v_reveal boolean;
begin
  perform public.ensure_teacher_role();
  if public.current_classroom_id() is distinct from p_classroom_id then
    raise exception '[RB2] other classroom denied' using errcode='P0980';
  end if;

  select coalesce(s.reveal_probabilities, true)
    into v_reveal
  from public.random_box_settings s
  where s.classroom_id=p_classroom_id and s.random_box_key=p_random_box_key;
  if v_reveal is null then v_reveal := true; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'reward_code', c.reward_code,
    'label', c.reward_label,
    'kind', c.reward_kind,
    'weight_bp', c.weight_bp,
    'probability_percent', c.weight_bp::numeric/100,
    'display_order', c.display_order
  ) order by c.display_order), '[]'::jsonb)
  into v_rewards
  from public.random_box_reward_catalog c
  where c.classroom_id=p_classroom_id
    and c.random_box_key=p_random_box_key
    and c.is_active=true;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', p.id, 'name', p.preset_name, 'weights', p.weights, 'updated_at', p.updated_at
  ) order by p.preset_name, p.id), '[]'::jsonb)
  into v_presets
  from public.random_box_probability_presets p
  where p.classroom_id=p_classroom_id and p.random_box_key=p_random_box_key;

  select coalesce(jsonb_agg(x.obj order by x.created_at desc, x.id desc), '[]'::jsonb)
  into v_history
  from (
    select h.id, h.created_at, jsonb_build_object(
      'id', h.id, 'created_at', h.created_at,
      'previous_weights', h.previous_weights,
      'new_weights', h.new_weights,
      'reveal_probabilities', h.reveal_probabilities,
      'change_note', h.change_note
    ) as obj
    from public.random_box_probability_history h
    where h.classroom_id=p_classroom_id and h.random_box_key=p_random_box_key
    order by h.created_at desc, h.id desc
    limit 20
  ) x;

  return jsonb_build_object(
    'classroom_id', p_classroom_id,
    'random_box_key', p_random_box_key,
    'reveal_probabilities', v_reveal,
    'rewards', v_rewards,
    'presets', v_presets,
    'history', v_history
  );
end;
$$;

create or replace function public.teacher_save_random_box_probability_config(
  p_classroom_id integer,
  p_random_box_key text,
  p_weights jsonb,
  p_reveal_probabilities boolean,
  p_change_note text default null
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_old jsonb; v_count integer; v_payload_count integer; v_sum integer;
begin
  perform public.ensure_teacher_role();
  if public.current_classroom_id() is distinct from p_classroom_id then
    raise exception '[RB2] other classroom denied' using errcode='P0981';
  end if;
  if p_weights is null or jsonb_typeof(p_weights) <> 'object' then
    raise exception '[RB2] weights must be a json object' using errcode='P0982';
  end if;

  select count(*), jsonb_object_agg(reward_code, weight_bp order by display_order)
    into v_count, v_old
  from public.random_box_reward_catalog
  where classroom_id=p_classroom_id and random_box_key=p_random_box_key and is_active=true;

  if v_count=0 then raise exception '[RB2] reward catalog not found' using errcode='P0983'; end if;
  select count(*) into v_payload_count from jsonb_object_keys(p_weights);
  if v_payload_count <> v_count then raise exception '[RB2] reward count mismatch' using errcode='P0984'; end if;

  if exists (
    select 1 from public.random_box_reward_catalog c
    where c.classroom_id=p_classroom_id and c.random_box_key=p_random_box_key and c.is_active=true
      and not (p_weights ? c.reward_code)
  ) then raise exception '[RB2] missing reward code' using errcode='P0985'; end if;

  if exists (
    select 1 from jsonb_each_text(p_weights) e
    where e.value !~ '^[0-9]+$' or e.value::integer <= 0
  ) then raise exception '[RB2] every weight must be a positive integer bp' using errcode='P0986'; end if;

  select coalesce(sum(value::integer),0) into v_sum from jsonb_each_text(p_weights);
  if v_sum <> 10000 then
    raise exception '[RB2] total probability must equal 100.00%% (10000 bp); got=%', v_sum using errcode='P0987';
  end if;

  with desired as (
    select c.id, c.display_order, (p_weights->>c.reward_code)::integer as new_weight
    from public.random_box_reward_catalog c
    where c.classroom_id=p_classroom_id and c.random_box_key=p_random_box_key and c.is_active=true
  ), ranged as (
    select id, new_weight,
      1 + coalesce(sum(new_weight) over (order by display_order rows between unbounded preceding and 1 preceding),0) as new_min,
      sum(new_weight) over (order by display_order rows between unbounded preceding and current row) as new_max
    from desired
  )
  update public.random_box_reward_catalog c
  set weight_bp=r.new_weight, min_roll=r.new_min, max_roll=r.new_max
  from ranged r where c.id=r.id;

  insert into public.random_box_settings(classroom_id, random_box_key, reveal_probabilities, updated_at, updated_by)
  values(p_classroom_id, p_random_box_key, coalesce(p_reveal_probabilities,true), now(), auth.uid())
  on conflict (classroom_id, random_box_key) do update
    set reveal_probabilities=excluded.reveal_probabilities,
        updated_at=excluded.updated_at,
        updated_by=excluded.updated_by;

  insert into public.random_box_probability_history(
    classroom_id, random_box_key, previous_weights, new_weights,
    reveal_probabilities, changed_by, change_note
  ) values (
    p_classroom_id, p_random_box_key, coalesce(v_old,'{}'::jsonb), p_weights,
    coalesce(p_reveal_probabilities,true), auth.uid(), nullif(btrim(coalesce(p_change_note,'')),'')
  );

  return public.teacher_get_random_box_probability_admin(p_classroom_id, p_random_box_key);
end;
$$;

create or replace function public.teacher_save_random_box_probability_preset(
  p_classroom_id integer,
  p_random_box_key text,
  p_preset_name text,
  p_weights jsonb
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_name text := nullif(btrim(coalesce(p_preset_name,'')),'');
  v_count integer; v_payload_count integer; v_sum integer;
begin
  perform public.ensure_teacher_role();
  if public.current_classroom_id() is distinct from p_classroom_id then
    raise exception '[RB2] other classroom denied' using errcode='P0988';
  end if;
  if v_name is null or length(v_name)>40 then
    raise exception '[RB2] preset name required (max 40)' using errcode='P0989';
  end if;
  if p_weights is null or jsonb_typeof(p_weights)<>'object' then
    raise exception '[RB2] weights must be a json object' using errcode='P0990';
  end if;

  select count(*) into v_count
  from public.random_box_reward_catalog
  where classroom_id=p_classroom_id and random_box_key=p_random_box_key and is_active=true;
  select count(*) into v_payload_count from jsonb_object_keys(p_weights);
  if v_count=0 or v_payload_count<>v_count then
    raise exception '[RB2] preset reward count mismatch' using errcode='P0991';
  end if;

  if exists (
    select 1 from public.random_box_reward_catalog c
    where c.classroom_id=p_classroom_id and c.random_box_key=p_random_box_key and c.is_active=true
      and not (p_weights ? c.reward_code)
  ) then raise exception '[RB2] preset missing reward code' using errcode='P0992'; end if;

  if exists (
    select 1 from jsonb_each_text(p_weights) e
    where e.value !~ '^[0-9]+$' or e.value::integer <= 0
  ) then raise exception '[RB2] preset weights must be positive integer bp' using errcode='P0993'; end if;

  select coalesce(sum(value::integer),0) into v_sum from jsonb_each_text(p_weights);
  if v_sum<>10000 then raise exception '[RB2] preset total must equal 10000 bp' using errcode='P0994'; end if;

  insert into public.random_box_probability_presets(
    classroom_id, random_box_key, preset_name, weights, created_by, updated_at
  ) values (p_classroom_id, p_random_box_key, v_name, p_weights, auth.uid(), now())
  on conflict (classroom_id, random_box_key, preset_name) do update
    set weights=excluded.weights, updated_at=now();

  return public.teacher_get_random_box_probability_admin(p_classroom_id, p_random_box_key);
end;
$$;

create or replace function public.teacher_delete_random_box_probability_preset(
  p_classroom_id integer,
  p_random_box_key text,
  p_preset_id bigint
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
begin
  perform public.ensure_teacher_role();
  if public.current_classroom_id() is distinct from p_classroom_id then
    raise exception '[RB2] other classroom denied' using errcode='P0995';
  end if;

  delete from public.random_box_probability_presets
  where id=p_preset_id and classroom_id=p_classroom_id and random_box_key=p_random_box_key;

  return public.teacher_get_random_box_probability_admin(p_classroom_id, p_random_box_key);
end;
$$;

create or replace function public.student_get_random_box_board()
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_student_id int; v_classroom_id int; v_role text; v_box_item_id bigint;
  v_box jsonb; v_rewards jsonb; v_history jsonb; v_reveal boolean;
begin
  v_student_id:=public.current_student_id();
  select classroom_id,role::text into v_classroom_id,v_role
  from public.students where id=v_student_id and transferred_at is null;

  if v_student_id is null or v_classroom_id is null or v_role not in ('STUDENT','STUDENT_LEADER','GUARD') then
    raise exception '[RB1] student login required' using errcode='P0962';
  end if;

  select id into v_box_item_id
  from public.market_items
  where classroom_id=v_classroom_id
    and metadata->>'random_box_key'='SUMMER_2026_RB1'
    and is_archived=false
  order by id limit 1;

  select jsonb_build_object(
    'item_id',mi.id,'name',mi.name,'description',mi.description,'image_url',mi.image_url,
    'owned_quantity',coalesce(si.owned_quantity,0),
    'reserved_quantity',coalesce(si.reserved_quantity,0),
    'available_quantity',coalesce(si.owned_quantity-si.reserved_quantity,0)
  ) into v_box
  from public.market_items mi
  left join public.student_inventory si on si.student_id=v_student_id and si.item_id=mi.id
  where mi.id=v_box_item_id;

  select coalesce(s.reveal_probabilities,true) into v_reveal
  from public.random_box_settings s
  where s.classroom_id=v_classroom_id and s.random_box_key='SUMMER_2026_RB1';
  if v_reveal is null then v_reveal:=true; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'reward_code',reward_code,'label',reward_label,'kind',reward_kind,
    'probability_percent',case when v_reveal then (weight_bp::numeric/100) else null end,
    'manual_required',(reward_kind='MANUAL')
  ) order by display_order),'[]'::jsonb)
  into v_rewards
  from public.random_box_reward_catalog
  where classroom_id=v_classroom_id
    and random_box_key='SUMMER_2026_RB1'
    and is_active=true;

  select coalesce(jsonb_agg(obj order by created_at desc,id desc),'[]'::jsonb)
  into v_history
  from (
    select id,created_at,jsonb_build_object(
      'opening_id',id,'reward_code',reward_code,'reward_label',reward_label,
      'reward_kind',reward_kind,'status',status,'created_at',created_at
    ) as obj
    from public.random_box_openings
    where student_id=v_student_id
    order by created_at desc,id desc limit 20
  ) x;

  return jsonb_build_object(
    'student_id',v_student_id,'classroom_id',v_classroom_id,
    'box',v_box,'rewards',v_rewards,'reveal_probabilities',v_reveal,'recent_openings',v_history
  );
end;
$$;

