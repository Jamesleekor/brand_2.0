CREATE TABLE private.newbie_support_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_id bigint NOT NULL,
  slot_id bigint NOT NULL,
  status text NOT NULL DEFAULT 'PENDING',
  evidence_type text NOT NULL,
  evidence_ref_id bigint NOT NULL,
  evidence_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  student_note text,
  requested_at timestamptz NOT NULL DEFAULT now(),
  reviewed_by uuid,
  reviewed_at timestamptz,
  review_note text,
  reward_bv bigint,
  reward_transaction_id bigint REFERENCES public.transactions(id) ON DELETE RESTRICT,
  reversal_transaction_id bigint REFERENCES public.transactions(id) ON DELETE RESTRICT,
  CONSTRAINT newbie_support_claims_program_id_uq UNIQUE(program_id,id),
  CONSTRAINT newbie_support_claims_slot_fk FOREIGN KEY(program_id,slot_id)
    REFERENCES private.newbie_support_program_quest_slots(program_id,id) ON DELETE RESTRICT,
  CONSTRAINT newbie_support_claims_status_ck CHECK (status IN ('PENDING','APPROVED','REJECTED','REVOKED','CANCELLED')),
  CONSTRAINT newbie_support_claims_evidence_ck CHECK (evidence_type IN (
    'P2P_SELL_REVIEW','P2P_BUY_REVIEW','COLLECTION_FIRST','COLLECTION_SECOND',
    'PUBLIC_REQUEST_DELIVERY','CLASS_HELP_BONUS_300','ARCADE_FOCUS_50000'
  )),
  CONSTRAINT newbie_support_claims_payload_ck CHECK (jsonb_typeof(evidence_payload)='object'),
  CONSTRAINT newbie_support_claims_note_ck CHECK (student_note IS NULL OR char_length(student_note) <= 500),
  CONSTRAINT newbie_support_claims_review_note_ck CHECK (review_note IS NULL OR char_length(review_note) <= 1000),
  CONSTRAINT newbie_support_claims_state_ck CHECK (
    (status='PENDING' AND reward_transaction_id IS NULL AND reversal_transaction_id IS NULL)
    OR (status='APPROVED' AND reward_bv IS NOT NULL AND reward_transaction_id IS NOT NULL AND reviewed_at IS NOT NULL AND reversal_transaction_id IS NULL)
    OR (status='REJECTED' AND reward_transaction_id IS NULL AND reversal_transaction_id IS NULL AND reviewed_at IS NOT NULL)
    OR (status='REVOKED' AND reward_bv IS NOT NULL AND reward_transaction_id IS NOT NULL AND reversal_transaction_id IS NOT NULL AND reviewed_at IS NOT NULL)
    OR (status='CANCELLED' AND reward_transaction_id IS NULL AND reversal_transaction_id IS NULL)
  )
);
CREATE UNIQUE INDEX newbie_support_claim_open_slot_uq
  ON private.newbie_support_claims(slot_id) WHERE status IN ('PENDING','APPROVED');
CREATE UNIQUE INDEX newbie_support_claim_open_evidence_uq
  ON private.newbie_support_claims(program_id,evidence_type,evidence_ref_id) WHERE status IN ('PENDING','APPROVED');
CREATE UNIQUE INDEX newbie_support_claim_reward_tx_uq
  ON private.newbie_support_claims(reward_transaction_id) WHERE reward_transaction_id IS NOT NULL;
CREATE UNIQUE INDEX newbie_support_claim_reversal_tx_uq
  ON private.newbie_support_claims(reversal_transaction_id) WHERE reversal_transaction_id IS NOT NULL;

