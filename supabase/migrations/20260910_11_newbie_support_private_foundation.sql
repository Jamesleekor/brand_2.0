  CONSTRAINT newbie_support_template_quests_sort_uq UNIQUE (template_id, sort_order),
  CONSTRAINT newbie_support_template_quests_target_ck CHECK (target_count BETWEEN 1 AND 100),
  CONSTRAINT newbie_support_template_quests_weight_ck CHECK (weight_per_completion BETWEEN 1 AND 1000),
  CONSTRAINT newbie_support_template_quests_sort_ck CHECK (sort_order > 0),
  CONSTRAINT newbie_support_template_quests_config_ck CHECK (jsonb_typeof(config)='object'),
