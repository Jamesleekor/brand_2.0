CREATE SCHEMA IF NOT EXISTS private;

REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA private TO authenticated;

ALTER DEFAULT PRIVILEGES IN SCHEMA private REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA private REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA private REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC, anon, authenticated;

CREATE TABLE private.newbie_support_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  version integer NOT NULL,
  name text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  regular_percent smallint NOT NULL DEFAULT 80,
  completion_percent smallint NOT NULL DEFAULT 20,
  mentor_min_count smallint NOT NULL DEFAULT 2,
  mentor_max_count smallint NOT NULL DEFAULT 3,
  mentor_min_valid_help smallint NOT NULL DEFAULT 3,
  mentor_base_reward_crystal bigint NOT NULL DEFAULT 2000,
  best_mentor_bonus_crystal bigint NOT NULL DEFAULT 1000,
  mentor_p2p_cap smallint NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT newbie_support_templates_code_version_uq UNIQUE (code, version),
  CONSTRAINT newbie_support_templates_regular_pct_ck CHECK (regular_percent BETWEEN 1 AND 100),
  CONSTRAINT newbie_support_templates_completion_pct_ck CHECK (completion_percent BETWEEN 0 AND 99),
  CONSTRAINT newbie_support_templates_pct_sum_ck CHECK (regular_percent + completion_percent = 100),
  CONSTRAINT newbie_support_templates_mentor_min_ck CHECK (mentor_min_count BETWEEN 1 AND 10),
  CONSTRAINT newbie_support_templates_mentor_max_ck CHECK (mentor_max_count BETWEEN mentor_min_count AND 10),
  CONSTRAINT newbie_support_templates_help_min_ck CHECK (mentor_min_valid_help BETWEEN 1 AND 100),
  CONSTRAINT newbie_support_templates_base_reward_ck CHECK (mentor_base_reward_crystal BETWEEN 0 AND 10000000),
  CONSTRAINT newbie_support_templates_best_reward_ck CHECK (best_mentor_bonus_crystal BETWEEN 0 AND 10000000),
  CONSTRAINT newbie_support_templates_p2p_cap_ck CHECK (mentor_p2p_cap BETWEEN 0 AND 100)
);

CREATE TABLE private.newbie_support_template_quests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
