    'PUBLIC_REQUEST_DELIVERY','CLASS_HELP_BONUS_300','ARCADE_FOCUS_50000'
  )),
  CONSTRAINT newbie_support_template_quests_verification_ck CHECK (verification_type IN (
    'P2P_SELL_REVIEW','P2P_BUY_REVIEW','COLLECTION_FIRST','COLLECTION_SECOND',
    'PUBLIC_REQUEST_DELIVERY','CLASS_HELP_BONUS_300','ARCADE_FOCUS_50000'
