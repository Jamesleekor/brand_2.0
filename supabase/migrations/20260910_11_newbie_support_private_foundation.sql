CREATE TABLE private.newbie_support_programs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  classroom_id integer NOT NULL REFERENCES public.classrooms(id) ON DELETE RESTRICT,
  student_id integer NOT NULL REFERENCES public.students(id) ON DELETE RESTRICT,
  template_id bigint NOT NULL REFERENCES private.newbie_support_templates(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'DRAFT',
  missed_opportunities integer NOT NULL,
  bv_per_opportunity bigint NOT NULL,
  total_restorable_bv bigint NOT NULL,
  regular_percent smallint NOT NULL,
  completion_percent smallint NOT NULL,
  regular_quest_pool_bv bigint NOT NULL,
  completion_bonus_bv bigint NOT NULL,
  total_quest_weight integer NOT NULL,
  start_on date NOT NULL,
  end_on date NOT NULL,
  mentor_min_count smallint NOT NULL,
  mentor_max_count smallint NOT NULL,
  mentor_min_valid_help smallint NOT NULL,
  mentor_base_reward_crystal bigint NOT NULL,
  best_mentor_bonus_crystal bigint NOT NULL,
  mentor_p2p_cap smallint NOT NULL,
  completion_requested_at timestamptz,
  best_mentor_assignment_id bigint,
  completion_bonus_transaction_id bigint REFERENCES public.transactions(id) ON DELETE RESTRICT,
  activated_at timestamptz,
  completed_at timestamptz,
  expired_at timestamptz,
  cancelled_at timestamptz,
  cancel_reason text,
  created_by uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT newbie_support_programs_status_ck CHECK (status IN ('DRAFT','ACTIVE','COMPLETED','EXPIRED','CANCELLED')),
  CONSTRAINT newbie_support_programs_missed_ck CHECK (missed_opportunities BETWEEN 1 AND 1000),
  CONSTRAINT newbie_support_programs_bv_per_ck CHECK (bv_per_opportunity BETWEEN 1 AND 10000),
  CONSTRAINT newbie_support_programs_total_bv_ck CHECK (total_restorable_bv BETWEEN 1 AND 10000000),
  CONSTRAINT newbie_support_programs_regular_pct_ck CHECK (regular_percent BETWEEN 1 AND 100),
  CONSTRAINT newbie_support_programs_completion_pct_ck CHECK (completion_percent BETWEEN 0 AND 99),
  CONSTRAINT newbie_support_programs_pct_sum_ck CHECK (regular_percent + completion_percent = 100),
  CONSTRAINT newbie_support_programs_date_ck CHECK (start_on <= end_on),
  CONSTRAINT newbie_support_programs_mentor_min_ck CHECK (mentor_min_count BETWEEN 1 AND 10),
  CONSTRAINT newbie_support_programs_mentor_max_ck CHECK (mentor_max_count BETWEEN mentor_min_count AND 10),
  CONSTRAINT newbie_support_programs_help_min_ck CHECK (mentor_min_valid_help BETWEEN 1 AND 100),
  CONSTRAINT newbie_support_programs_base_reward_ck CHECK (mentor_base_reward_crystal BETWEEN 0 AND 10000000),
  CONSTRAINT newbie_support_programs_best_reward_ck CHECK (best_mentor_bonus_crystal BETWEEN 0 AND 10000000),
  CONSTRAINT newbie_support_programs_p2p_cap_ck CHECK (mentor_p2p_cap BETWEEN 0 AND 100),
  CONSTRAINT newbie_support_programs_math_total_ck CHECK (total_restorable_bv = missed_opportunities::bigint * bv_per_opportunity),
  CONSTRAINT newbie_support_programs_math_regular_ck CHECK (regular_quest_pool_bv = (total_restorable_bv * regular_percent) / 100),
  CONSTRAINT newbie_support_programs_math_completion_ck CHECK (completion_bonus_bv = total_restorable_bv - regular_quest_pool_bv),
  CONSTRAINT newbie_support_programs_pool_nonneg_ck CHECK (regular_quest_pool_bv >= 0 AND completion_bonus_bv >= 0),
  CONSTRAINT newbie_support_programs_weight_ck CHECK (total_quest_weight > 0)
);
CREATE UNIQUE INDEX newbie_support_one_active_program_uq
