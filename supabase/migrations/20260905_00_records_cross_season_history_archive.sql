create table if not exists public.records_historical_entries (
  id bigint generated by default as identity primary key,
  record_key text not null unique,
  hall_key text not null,
  record_type text not null,
  title text not null,
  subtitle text,
  description text,
  subject_kind text not null default 'STUDENT',
  subject_display_name text not null,
  subject_brand_name text,
  subject_student_id integer references public.students(id) on delete set null,
  subject_guild_id integer references public.guilds(id) on delete set null,
  school_year integer,
  season_label text,
  period_label text,
  occurred_on date,
  rank_position integer,
  value_primary numeric,
  value_secondary numeric,
  denominator numeric,
  unit text,
  comparison_value numeric,
  source_kind text not null default 'CURATED',
  source_ref text,
  metadata jsonb not null default '{}'::jsonb,
  status text not null default 'ACTIVE',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint records_historical_entries_hall_key_check check (
    hall_key in (
      'PIONEERS',
      'THRONE',
      'REPEATED_CROWNS',
      'ASCENT',
      'GOLDEN_CHRONICLE',
      'GUILD_HEGEMONY',
      'ARCADE_RULERS',
      'CONSTELLATION',
      'SOVEREIGN_PROOF'
    )
  ),
  constraint records_historical_entries_subject_kind_check check (
    subject_kind in ('STUDENT','GUILD','SYSTEM','EMPTY_THRONE')
  ),
  constraint records_historical_entries_source_kind_check check (
    source_kind in ('CURATED','PRODUCTION_SNAPSHOT','PRODUCTION_DERIVED')
  ),
  constraint records_historical_entries_status_check check (
    status in ('ACTIVE','ARCHIVED')
  ),
  constraint records_historical_entries_rank_check check (
    rank_position is null or rank_position > 0
  )
);

comment on table public.records_historical_entries is
  'Cross-season Hall of Glory archive. Historical display-name snapshots are authoritative; current student/guild FK links are optional.';
comment on column public.records_historical_entries.record_key is
  'Stable semantic identity for idempotent historical seed/update operations.';
comment on column public.records_historical_entries.subject_display_name is
  'Historical snapshot name. Never reconstruct past people by joining current students.';
comment on column public.records_historical_entries.comparison_value is
  'Optional normalized value used only for cross-era comparison while value_primary preserves the displayed/original metric.';

