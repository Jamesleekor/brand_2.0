create or replace function public.student_get_records_hall_of_glory()
returns jsonb
language plpgsql
stable
security definer
set search_path = 'public', 'pg_temp'
as $$
declare
  v_classroom_id integer := public.current_classroom_id();
  v_student_id integer := public.current_student_id();
  v_entries jsonb;
begin
  if auth.uid() is null or v_classroom_id is null or v_student_id is null then
    raise exception '[RECORDS] authenticated classroom member context is required.' using errcode='P0930';
  end if;

  select coalesce(jsonb_agg(to_jsonb(q) order by q.hall_key, q.sort_order, q.rank_position nulls last, q.id), '[]'::jsonb)
  into v_entries
  from (
    select
      h.id,
      h.record_key,
      h.hall_key,
      h.record_type,
      h.title,
      h.subtitle,
      h.description,
      h.subject_kind,
      h.subject_display_name,
      h.subject_brand_name,
      h.school_year,
      h.season_label,
      h.period_label,
      h.occurred_on,
      h.rank_position,
      h.value_primary,
      h.value_secondary,
      h.denominator,
      h.unit,
      h.comparison_value,
      h.source_kind,
      h.metadata,
      h.sort_order
    from public.records_historical_entries h
    where h.status='ACTIVE'
  ) q;

  return jsonb_build_object(
    'entries', v_entries,
    'gap_eras', jsonb_build_array(
      jsonb_build_object(
        'start_year', 2024,
        'end_year', 2025,
        'title', '공백의 2년',
        'subtitle', '기록이 침묵한 시대'
      )
    )
  );
end;
$$;

