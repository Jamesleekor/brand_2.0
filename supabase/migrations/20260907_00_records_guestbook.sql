create or replace function public.teacher_delete_records_guestbook(
  p_entry_id bigint
)
returns boolean
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_classroom_id integer := public.current_classroom_id();
  v_owner_teacher_user_id uuid;
  v_deleted_id bigint;
begin
  perform public.ensure_teacher_role();

  if auth.uid() is null or v_classroom_id is null then
    raise exception '[RECORDS_GUESTBOOK] authenticated teacher context is required.'
      using errcode = 'P0948';
  end if;

  select c.teacher_user_id
    into v_owner_teacher_user_id
  from public.classrooms c
  where c.id = v_classroom_id;

  delete from public.records_guestbook_entries e
  where e.id = p_entry_id
    and e.owner_teacher_user_id = v_owner_teacher_user_id
  returning e.id into v_deleted_id;

  if v_deleted_id is null then
    raise exception '[RECORDS_GUESTBOOK] guestbook entry not found in this teacher lineage.'
      using errcode = 'P0949';
  end if;

  return true;
end;
$function$;

